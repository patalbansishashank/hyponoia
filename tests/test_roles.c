/*
 * test_roles.c — role derivation and the role audit.
 *
 * One test per derivation rule, each against a real fixture tree; the
 * precedence ladder; the A5 fail-closed default; and the A7 audit, which
 * must REPORT a contradiction and leave the role untouched.
 *
 * The two real-registry tests (vendored, upstream set) run against THIS
 * repository's own registry files, because A2/A4's whole claim is "derive
 * from the registry that already exists" — a test that only ever reads a
 * fixture invented here would never notice the real format drifting.
 */
#include "test_framework.h"
#include "test_helpers.h"

#include "discover/role.h"

#include <stdio.h>
#include <string.h>

/* 64 hex chars — the shape scripts/vendored-checksums.txt actually holds.
 * The VALUE is irrelevant to role derivation; only coverage is read. */
#define FAKE_SHA "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"

static const char MARKED_HEAD[] = "/* Code generated by fixture-gen. DO NOT EDIT. */\nint x;\n";
static const char PLAIN_HEAD[] = "/* hand-written */\nint y;\n";

/* Write a fixture registry repo declaring example upstreams in the two real
 * formats (provenance audit LIBS/FORKS lines, grammar manifest table row). */
static int write_registry_fixture(const char *reg_root) {
    int rc = th_write_file(TH_PATH(reg_root, "scripts/audit-license-provenance.py"),
                           "LIBS = {\n"
                           "    \"vendored/example-lib\": (\"Example-Org/Example-Lib\", None),\n"
                           "}\n"
                           "FORKS = {\n"
                           "    \"thing\": \"other-org/thing-fork\",\n"
                           "}\n");
    rc |= th_write_file(TH_PATH(reg_root, "internal/hyp/vendored/grammars/MANIFEST.md"),
                        "| grammar | abi | upstream | pinned | verdict | ok |\n"
                        "|---|---|---|---|---|---|\n"
                        "| ada | 14 | briot/tree-sitter-ada | `abc123` | VERIFIED-BOTH | ok |\n");
    return rc;
}

/* Point a fixture repo's origin at url via a plain .git/config. */
static int write_repo_with_origin(const char *repo_root, const char *url) {
    char config[512];
    (void)snprintf(config, sizeof config,
                   "[core]\n\trepositoryformatversion = 0\n"
                   "[remote \"origin\"]\n\turl = %s\n\tfetch = +refs/heads/*:refs/remotes/origin/*\n",
                   url);
    return th_write_file(TH_PATH(repo_root, ".git/config"), config);
}

/* ════════════════════════════════════════════════════════════════════
 * A2 — vendored, derived from the checksum registry
 * ════════════════════════════════════════════════════════════════════ */

TEST(roles_vendored_derived_from_fixture_registry) {
    char base[256];
    char *tmp = th_mktempdir("hyp_roles_a2");
    if (!tmp) FAIL("th_mktempdir returned NULL");
    snprintf(base, sizeof base, "%s", tmp);

    ASSERT_EQ(th_write_file(TH_PATH(base, "host/scripts/vendored-checksums.txt"),
                            FAKE_SHA "  third_party/libfoo/foo.c\n" FAKE_SHA
                                     "  third_party/libfoo/LICENSE\n"),
              0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/third_party/libfoo/foo.c"), "int foo;\n"), 0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/third_party/other/bar.c"), "int bar;\n"), 0);

    char ev[HYP_ROLE_EVIDENCE_MAX + 1];
    ev[0] = '\0';
    ASSERT_TRUE(hyp_role_is_vendored(TH_PATH(base, "host/third_party/libfoo"), ev, sizeof ev));
    /* The evidence names the registry, not a guess. */
    ASSERT_NOT_NULL(strstr(ev, "vendored-checksums.txt"));

    /* An unregistered sibling is NOT vendored — coverage comes from the
     * registry's entries, never from the directory's neighbourhood. */
    ASSERT_FALSE(hyp_role_is_vendored(TH_PATH(base, "host/third_party/other"), NULL, 0));
    /* Nor is the repository that CARRIES the manifest. */
    ASSERT_FALSE(hyp_role_is_vendored(TH_PATH(base, "host"), NULL, 0));

    hyp_role_result_t r;
    ASSERT_TRUE(hyp_role_derive(TH_PATH(base, "host/third_party/libfoo"), NULL, &r));
    ASSERT_EQ(r.role, HYP_ROLE_VENDORED);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DERIVED_VENDORED_REGISTRY);

    th_cleanup(base);
    PASS();
}

TEST(roles_vendored_coverage_respects_path_boundaries) {
    /* "third_party/libfoobar/x.c" must not cover "third_party/libfoo" — a
     * prefix match without a component boundary is a different tree. */
    char base[256];
    char *tmp = th_mktempdir("hyp_roles_a2b");
    if (!tmp) FAIL("th_mktempdir returned NULL");
    snprintf(base, sizeof base, "%s", tmp);

    ASSERT_EQ(th_write_file(TH_PATH(base, "host/scripts/vendored-checksums.txt"),
                            FAKE_SHA "  third_party/libfoobar/x.c\n"),
              0);
    ASSERT_EQ(th_mkdir_p(TH_PATH(base, "host/third_party/libfoo")), 0);
    ASSERT_FALSE(hyp_role_is_vendored(TH_PATH(base, "host/third_party/libfoo"), NULL, 0));

    th_cleanup(base);
    PASS();
}

TEST(roles_vendored_reads_the_registry_that_already_exists) {
    /* THIS repository's registry, in its real format. If these fail, either
     * the test is not running from the repo root (a harness bug) or the
     * registry format changed and role derivation silently stopped seeing
     * vendored code — exactly the drift this test exists to catch. */
    if (!hyp_file_exists("scripts/vendored-checksums.txt"))
        FAIL("must run from the repository root");

    char ev[HYP_ROLE_EVIDENCE_MAX + 1];
    ev[0] = '\0';
    ASSERT_TRUE(hyp_role_is_vendored("vendored/llama.cpp", ev, sizeof ev));
    ASSERT_NOT_NULL(strstr(ev, "vendored/llama.cpp"));
    ASSERT_TRUE(hyp_role_is_vendored("internal/hyp/vendored/lz4", NULL, 0));
    ASSERT_FALSE(hyp_role_is_vendored("src", NULL, 0));
    PASS();
}

