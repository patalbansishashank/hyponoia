    ASSERT_EQ(th_write_file(TH_PATH(base, "gen/b.c"), MARKED_HEAD), 0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "gen/sub/c.c"), MARKED_HEAD), 0);
