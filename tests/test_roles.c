TEST(roles_upstream_derived_from_remote_and_registry) {
    char base[256];
    char *tmp = th_mktempdir("hyp_roles_a4c");
    if (!tmp) FAIL("th_mktempdir returned NULL");
    snprintf(base, sizeof base, "%s", tmp);

    ASSERT_EQ(write_registry_fixture(TH_PATH(base, "reg")), 0);
    hyp_role_upstreams_t set;
    hyp_role_upstreams_init(&set);
    ASSERT_TRUE(hyp_role_upstreams_load(&set, TH_PATH(base, "reg")));
    ASSERT_EQ(set.count, 3); /* LIBS + FORKS + grammar manifest rows */

    ASSERT_EQ(write_repo_with_origin(TH_PATH(base, "clone"),
                                     "https://github.com/Example-Org/Example-Lib.git"),
              0);

    hyp_role_ctx_t ctx = {0};
    ctx.known_upstreams = &set;

    char ev[HYP_ROLE_EVIDENCE_MAX + 1];
    ev[0] = '\0';
    ASSERT_TRUE(hyp_role_is_upstream(TH_PATH(base, "clone"), &ctx, ev, sizeof ev));
    ASSERT_NOT_NULL(strstr(ev, "example-org/example-lib"));

    hyp_role_result_t r;
    ASSERT_TRUE(hyp_role_derive(TH_PATH(base, "clone"), &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_UPSTREAM);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DERIVED_REMOTE);

    /* THE OTHER HALF OF THE RULE: a checkout whose origin IS the workspace's
     * own origin is another copy of this project, never its upstream. */
    ctx.workspace_origin = "example-org/example-lib";
    ASSERT_FALSE(hyp_role_is_upstream(TH_PATH(base, "clone"), &ctx, NULL, 0));
    ASSERT_TRUE(hyp_role_derive(TH_PATH(base, "clone"), &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_REFERENCE);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DEFAULT_REFERENCE);

    /* A remote in NO registry is not upstream of anything here. */
    ctx.workspace_origin = NULL;
    ASSERT_EQ(write_repo_with_origin(TH_PATH(base, "rando"),
                                     "https://github.com/somebody/inspiration.git"),
              0);
    ASSERT_FALSE(hyp_role_is_upstream(TH_PATH(base, "rando"), &ctx, NULL, 0));

    hyp_role_upstreams_free(&set);
    th_cleanup(base);
    PASS();
}

TEST(roles_upstreams_load_reads_the_existing_registries) {
    /* The real files, the real formats: the provenance audit's LIBS table
     * (ggml-org/llama.cpp is the unit's own named example), its FORKS table,
     * and the grammar manifest's verified-upstream rows. */
    if (!hyp_file_exists("scripts/audit-license-provenance.py"))
        FAIL("must run from the repository root");

    hyp_role_upstreams_t set;
    hyp_role_upstreams_init(&set);
    ASSERT_TRUE(hyp_role_upstreams_load(&set, "."));
    ASSERT_GT(set.count, 0);

    bool llama = false;
    bool ada = false;
    bool cfml = false;
    for (size_t i = 0; i < set.count; i++) {
        if (strcmp(set.entries[i].coord, "ggml-org/llama.cpp") == 0) llama = true;
        if (strcmp(set.entries[i].coord, "briot/tree-sitter-ada") == 0) ada = true;
        if (strcmp(set.entries[i].coord, "cfmleditor/tree-sitter-cfml") == 0) cfml = true;
    }
    ASSERT_TRUE(llama);
    ASSERT_TRUE(ada);
    ASSERT_TRUE(cfml);

    /* Every loaded entry is a well-formed coordinate — prose strings that
     * happen to follow a colon in the Python source must not leak in. */
    for (size_t i = 0; i < set.count; i++) {
        ASSERT_NOT_NULL(strchr(set.entries[i].coord, '/'));
        ASSERT_NULL(strchr(set.entries[i].coord, ' '));
        ASSERT_NULL(strchr(set.entries[i].coord, '('));
    }

    hyp_role_upstreams_free(&set);
    PASS();
}

