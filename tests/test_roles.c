    ASSERT_EQ(th_mkdir_p(TH_PATH(base, "loose/build")), 0);
    ASSERT_FALSE(hyp_role_is_gitignored(TH_PATH(base, "loose/build"), NULL, 0));

    hyp_role_result_t r;
