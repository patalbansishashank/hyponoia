/* ════════════════════════════════════════════════════════════════════
 * Precedence — declared > vendored > gitignore > do-not-edit > remote
 *              > default, one ladder, every rung real
 * ════════════════════════════════════════════════════════════════════ */

TEST(roles_precedence_ladder) {
    char base[256];
    char *tmp = th_mktempdir("hyp_roles_prec");
    if (!tmp) FAIL("th_mktempdir returned NULL");
    snprintf(base, sizeof base, "%s", tmp);

    /* One candidate carrying EVERY signal at once. */
    ASSERT_EQ(th_mkdir_p(TH_PATH(base, "host/.git")), 0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/.gitignore"), "vendor_gen/\n"), 0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/scripts/vendored-checksums.txt"),
                            FAKE_SHA "  vendor_gen/lib/gen1.h\n"),
              0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/vendor_gen/lib/gen1.h"), MARKED_HEAD), 0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/vendor_gen/lib/gen2.h"), MARKED_HEAD), 0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/vendor_gen/lib/gen3.h"), MARKED_HEAD), 0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/vendor_gen/lib/notes.txt"), PLAIN_HEAD), 0);
    ASSERT_EQ(write_repo_with_origin(TH_PATH(base, "host/vendor_gen/lib"),
                                     "https://github.com/Example-Org/Example-Lib.git"),
              0);

    ASSERT_EQ(write_registry_fixture(TH_PATH(base, "reg")), 0);
    hyp_role_upstreams_t set;
    hyp_role_upstreams_init(&set);
    ASSERT_TRUE(hyp_role_upstreams_load(&set, TH_PATH(base, "reg")));

    hyp_role_ctx_t ctx = {0};
    ctx.known_upstreams = &set;
    hyp_role_result_t r;
    char cand[512];
    (void)snprintf(cand, sizeof cand, "%s/host/vendor_gen/lib", base);

    /* 1. Declaration outranks every derivation. */
    ctx.declared = "upstream";
    ASSERT_TRUE(hyp_role_derive(cand, &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_UPSTREAM);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DECLARED_TOML);

    /* 2. No declaration: the checksum registry wins. */
    ctx.declared = NULL;
    ASSERT_TRUE(hyp_role_derive(cand, &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_VENDORED);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DERIVED_VENDORED_REGISTRY);

    /* 3. Registry gone: gitignore speaks next. */
    ASSERT_EQ(th_rmtree(TH_PATH(base, "host/scripts")), 0);
    ASSERT_TRUE(hyp_role_derive(cand, &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_GENERATED);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DERIVED_GITIGNORE);

    /* 4. Gitignore gone: the DO-NOT-EDIT majority speaks. */
    ASSERT_EQ(th_rmtree(TH_PATH(base, "host/.gitignore")), 0);
    ASSERT_TRUE(hyp_role_derive(cand, &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_GENERATED);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DERIVED_DO_NOT_EDIT);

    /* 5. Markers gone: the remote speaks. */
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/vendor_gen/lib/gen1.h"), PLAIN_HEAD), 0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/vendor_gen/lib/gen2.h"), PLAIN_HEAD), 0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/vendor_gen/lib/gen3.h"), PLAIN_HEAD), 0);
    ASSERT_TRUE(hyp_role_derive(cand, &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_UPSTREAM);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DERIVED_REMOTE);

    /* 6. No remote context left: the fail-closed floor. */
    ctx.known_upstreams = NULL;
    ASSERT_TRUE(hyp_role_derive(cand, &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_REFERENCE);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DEFAULT_REFERENCE);

    hyp_role_upstreams_free(&set);
    th_cleanup(base);
    PASS();
}

/* ════════════════════════════════════════════════════════════════════
 * A7 — the audit reports; it NEVER reassigns
 * ════════════════════════════════════════════════════════════════════ */

TEST(roles_audit_reports_member_do_not_edit_contradiction) {
    char base[256];
    char *tmp = th_mktempdir("hyp_roles_a7");
    if (!tmp) FAIL("th_mktempdir returned NULL");
    snprintf(base, sizeof base, "%s", tmp);

    /* Ten files, nine generated — the unit's own fixture: a repo tagged
     * member whose files are overwhelmingly DO NOT EDIT. */
    char rel[64];
    for (int i = 0; i < 9; i++) {
        (void)snprintf(rel, sizeof rel, "tagged/gen%d.c", i);
        ASSERT_EQ(th_write_file(TH_PATH(base, rel), MARKED_HEAD), 0);
    }
    ASSERT_EQ(th_write_file(TH_PATH(base, "tagged/main.c"), PLAIN_HEAD), 0);

    hyp_role_ctx_t ctx = {0};
    ctx.declared = "member";
    hyp_role_result_t r;
    ASSERT_TRUE(hyp_role_derive(TH_PATH(base, "tagged"), &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_MEMBER);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DECLARED_TOML);

    hyp_role_result_t before = r;
    hyp_role_contradiction_t contra[4];
    size_t n = hyp_role_audit(TH_PATH(base, "tagged"), &r, &ctx, contra, 4);
    ASSERT_EQ(n, 1);
    ASSERT_EQ(contra[0].kind, HYP_ROLE_CONTRA_MEMBER_DO_NOT_EDIT);
    ASSERT_NOT_NULL(strstr(contra[0].evidence, "9 of 10"));

    /* REPORT, not absorb: the resolved role is unchanged after the audit —
     * role, source and evidence all. This assertion IS the A7 contract. */
    ASSERT_EQ(r.role, HYP_ROLE_MEMBER);
    ASSERT_EQ(r.source, HYP_ROLE_SRC_DECLARED_TOML);
    ASSERT_EQ(before.role, r.role);
    ASSERT_EQ(before.source, r.source);
    ASSERT_STR_EQ(before.evidence, r.evidence);

    th_cleanup(base);
    PASS();
}

TEST(roles_audit_reports_member_vendored_and_upstream_contradictions) {
    char base[256];
    char *tmp = th_mktempdir("hyp_roles_a7b");
    if (!tmp) FAIL("th_mktempdir returned NULL");
    snprintf(base, sizeof base, "%s", tmp);

    /* member, but registered vendored AND cloned from a known upstream AND
     * overwhelmingly DO-NOT-EDIT: three contradictions. */
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/scripts/vendored-checksums.txt"),
                            FAKE_SHA "  third_party/libfoo/gen.c\n"),
              0);
    ASSERT_EQ(th_write_file(TH_PATH(base, "host/third_party/libfoo/gen.c"), MARKED_HEAD), 0);
    ASSERT_EQ(write_repo_with_origin(TH_PATH(base, "host/third_party/libfoo"),
                                     "https://github.com/Example-Org/Example-Lib.git"),
              0);
    ASSERT_EQ(write_registry_fixture(TH_PATH(base, "reg")), 0);

    hyp_role_upstreams_t set;
    hyp_role_upstreams_init(&set);
    ASSERT_TRUE(hyp_role_upstreams_load(&set, TH_PATH(base, "reg")));

    hyp_role_ctx_t ctx = {0};
    ctx.declared = "member";
    ctx.known_upstreams = &set;
    hyp_role_result_t r;
    ASSERT_TRUE(hyp_role_derive(TH_PATH(base, "host/third_party/libfoo"), &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_MEMBER);

    /* cap 1 < findings 3: the return value is the TRUE count — a floor is
     * only a floor when nothing above it is silently dropped. */
    hyp_role_contradiction_t one[1];
    size_t n = hyp_role_audit(TH_PATH(base, "host/third_party/libfoo"), &r, &ctx, one, 1);
    ASSERT_EQ(n, 3);
    ASSERT_EQ(one[0].kind, HYP_ROLE_CONTRA_MEMBER_VENDORED);
    ASSERT_EQ(r.role, HYP_ROLE_MEMBER); /* still member; still only reported */

    hyp_role_upstreams_free(&set);
    th_cleanup(base);
    PASS();
}

TEST(roles_audit_is_asymmetric_and_silent_when_consistent) {
    char base[256];
    char *tmp = th_mktempdir("hyp_roles_a7c");
    if (!tmp) FAIL("th_mktempdir returned NULL");
    snprintf(base, sizeof base, "%s", tmp);

    /* A consistent member: nothing to report. */
    ASSERT_EQ(th_write_file(TH_PATH(base, "mine/src/main.c"), PLAIN_HEAD), 0);
    hyp_role_ctx_t ctx = {0};
    ctx.declared = "member";
    hyp_role_result_t r;
    ASSERT_TRUE(hyp_role_derive(TH_PATH(base, "mine"), &ctx, &r));
    hyp_role_contradiction_t contra[4];
    ASSERT_EQ(hyp_role_audit(TH_PATH(base, "mine"), &r, &ctx, contra, 4), 0);

    /* A read-only role over a generated tree is NOT audited — vendored code
     * full of DO-NOT-EDIT headers is the world working as designed, and a
     * wrong read-only tag is recoverable, not hazardous. */
    ASSERT_EQ(th_write_file(TH_PATH(base, "gen/a.c"), MARKED_HEAD), 0);
    ctx.declared = "vendored";
    ASSERT_TRUE(hyp_role_derive(TH_PATH(base, "gen"), &ctx, &r));
    ASSERT_EQ(r.role, HYP_ROLE_VENDORED);
    ASSERT_EQ(hyp_role_audit(TH_PATH(base, "gen"), &r, &ctx, contra, 4), 0);

    th_cleanup(base);
    PASS();
}

/* ── Wire names — both directions, so the resolver and the TOML agree ── */

TEST(roles_names_round_trip) {
    static const hyp_role_t all[] = {HYP_ROLE_MEMBER, HYP_ROLE_VENDORED, HYP_ROLE_GENERATED,
                                     HYP_ROLE_UPSTREAM, HYP_ROLE_REFERENCE};
    for (size_t i = 0; i < sizeof all / sizeof all[0]; i++) {
        hyp_role_t parsed;
        ASSERT_TRUE(hyp_role_parse(hyp_role_name(all[i]), &parsed));
        ASSERT_EQ(parsed, all[i]);
    }
    hyp_role_t out;
    ASSERT_FALSE(hyp_role_parse("Member", &out)); /* strict: one spelling */
    ASSERT_FALSE(hyp_role_parse("", &out));
    ASSERT_FALSE(hyp_role_parse(NULL, &out));

    /* The six disclosure tokens, verbatim from the plan. */
    ASSERT_STR_EQ(hyp_role_source_name(HYP_ROLE_SRC_DECLARED_TOML), "declared-toml");
    ASSERT_STR_EQ(hyp_role_source_name(HYP_ROLE_SRC_DERIVED_VENDORED_REGISTRY),
                  "derived-vendored-registry");
    ASSERT_STR_EQ(hyp_role_source_name(HYP_ROLE_SRC_DERIVED_GITIGNORE), "derived-gitignore");
    ASSERT_STR_EQ(hyp_role_source_name(HYP_ROLE_SRC_DERIVED_DO_NOT_EDIT), "derived-do-not-edit");
    ASSERT_STR_EQ(hyp_role_source_name(HYP_ROLE_SRC_DERIVED_REMOTE), "derived-remote");
    ASSERT_STR_EQ(hyp_role_source_name(HYP_ROLE_SRC_DEFAULT_REFERENCE), "default-reference");
    PASS();
}

